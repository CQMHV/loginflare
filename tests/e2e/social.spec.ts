import { createHash, randomUUID } from 'node:crypto';
import { expect, test } from './fixtures';
import { testOrigin } from './runtime';
import { executeLocal, removeLocalApplications, removeLocalFixtures } from './database';
import { snapshotEmails, waitForMail } from './mailbox';
import { authenticatorCode } from '../totp';
import { defaultConnectionConfig } from '../../src/shared/social';

test('manages a connector and completes social registration, step-up, MFA and downstream consent', async ({ page, context }) => {
    test.setTimeout(150_000);
    const administrator = `ui-${randomUUID()}@loginflare.test`, email = `ui-${randomUUID()}@loginflare.test`, subject = `ui-social-${randomUUID()}`;
    const password = 'Social-browser-password-917!';
    const connectionName = `Google ${randomUUID().slice(0, 8)}`;
    const secondConnectionName = `Second Google ${randomUUID().slice(0, 8)}`;
    let connectionId = '', secondConnectionId = '', clientId = '';
    await context.route('https://accounts.google.com/**', async (route) => {
        const authorization = new URL(route.request().url());
        const code = Buffer.from(JSON.stringify({ sub: subject, email, name: 'Social Browser User', nonce: authorization.searchParams.get('nonce') })).toString('base64url');
        const callback = new URL(authorization.searchParams.get('redirect_uri')!);
        callback.searchParams.set('code', code); callback.searchParams.set('state', authorization.searchParams.get('state')!);
        await route.fulfill({ status: 302, headers: { Location: callback.href }, body: '' });
    });
    await context.route('https://social-app.example.com/**', (route) => route.fulfill({ contentType: 'text/html', body: '<p>Social application callback</p>' }));
    try {
        const before = await snapshotEmails();
        const signup = await context.request.post('/api/auth/sign-up/email', { headers: { Origin: testOrigin, 'x-captcha-response': 'isolated-e2e-captcha-token' }, data: { name: 'Social Administrator', username: `ui_${randomUUID().replaceAll('-', '').slice(0, 20)}`, email: administrator, password, locale: 'en-US', callbackURL: `${testOrigin}/en-us/verified` } });
        expect(signup.status(), await signup.text()).toBe(200);
        await page.goto(await waitForMail(before, 'verify'));
        expect((await context.request.post('/api/auth/sign-in/email', { headers: { Origin: testOrigin, 'x-captcha-response': 'isolated-e2e-captcha-token' }, data: { email: administrator, password } })).status()).toBe(200);
        executeLocal(`UPDATE "user" SET "role" = 'admin' WHERE "email" = '${administrator}';`);
        await page.goto('/en-us/admin/social-connections');
        await page.getByRole('button', { name: 'Create connection', exact: true }).click();
        await page.getByLabel('Display name', { exact: true }).fill(connectionName);
        await page.getByLabel('Client ID', { exact: true }).fill('isolated-social-client');
        await page.getByLabel('Client secret', { exact: true }).fill('isolated-social-secret');
        const iconChooser = page.waitForEvent('filechooser');
        await page.getByRole('button', { name: 'Edit connection icon', exact: true }).click();
        await (await iconChooser).setFiles({ name: 'provider.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#6750a4"/></svg>') });
        const iconEditor = page.locator('md-dialog.image-crop-dialog');
        await expect(iconEditor.getByRole('button', { name: 'Use icon', exact: true })).toBeEnabled();
        await iconEditor.getByRole('button', { name: 'Use icon', exact: true }).click();
        await expect(iconEditor).toHaveCount(0);
        const iconPreview = page.locator('.provider-icon-preview img');
        await expect(iconPreview).toHaveAttribute('src', /^\/social\/icons\/[a-f0-9-]+$/);
        const iconUrl = (await iconPreview.getAttribute('src'))!;
        expect((await context.request.get(iconUrl)).status()).toBe(200);
        await page.getByRole('button', { name: 'Save changes', exact: true }).click();
        await expect(page.getByLabel('Callback URL')).toHaveValue(/\/api\/auth\/callback\/[a-f0-9-]+$/);
        connectionId = (await page.getByLabel('Callback URL').inputValue()).split('/').at(-1)!;
        await expect(page.getByRole('checkbox', { name: 'Enabled', exact: true })).not.toBeChecked();
        await expect(page.getByLabel('Client secret', { exact: true })).toHaveValue('');
        await page.getByRole('button', { name: 'Test sign-in', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Connection test' })).toBeVisible();
        await expect(page.getByText('Authentication succeeded. No account was created or linked.')).toBeVisible();
        expect((await (await context.request.get('/api/auth/get-session')).json()).user.email).toBe(administrator);
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        await page.getByRole('button', { name: 'Edit connection', exact: true }).click();
        await page.getByRole('checkbox', { name: 'Enabled', exact: true }).check();
        await page.getByRole('button', { name: 'Save changes', exact: true }).click();
        await expect(page.getByText('Your changes have been saved.', { exact: true })).toBeVisible();
        const providers = await (await context.request.get('/api/social/providers')).json();
        expect(providers.providers.find((provider: { id: string }) => provider.id === connectionId)?.iconUrl).toBe(iconUrl);
        const secondInput = { name: secondConnectionName, type: 'google', config: { ...defaultConnectionConfig('google'), clientId: 'isolated-social-client' }, clientSecret: 'isolated-social-secret', enabled: false, archived: false, revision: 0 };
        const secondCreated = await context.request.post('/api/admin/social-connections', { headers: { Origin: testOrigin }, data: secondInput });
        expect(secondCreated.status(), await secondCreated.text()).toBe(201);
        secondConnectionId = (await secondCreated.json()).id;
        const secondEnabled = await context.request.patch(`/api/admin/social-connections/${secondConnectionId}`, { headers: { Origin: testOrigin }, data: { ...secondInput, enabled: true } });
        expect(secondEnabled.status(), await secondEnabled.text()).toBe(200);
        const app = await context.request.post('/api/admin/applications', { headers: { Origin: testOrigin }, data: { name: `ui-oauth-${randomUUID()}`, type: 'spa', redirectUris: ['https://social-app.example.com/callback'], postLogoutRedirectUris: ['https://social-app.example.com/'], scopes: ['openid', 'profile', 'email'] } });
        expect(app.status(), await app.text()).toBe(201); clientId = (await app.json()).application.clientId;
        await context.request.post('/api/auth/sign-out', { headers: { Origin: testOrigin }, data: {} });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.goto('/zh-cn/select-account');
        await page.getByRole('button', { name: '使用其他账号', exact: true }).click();
        await page.getByRole('button', { name: `使用 ${connectionName} 继续`, exact: true }).click();
        await expect(page.getByRole('heading', { name: '完成登录' })).toBeVisible();
        await page.getByRole('button', { name: '继续', exact: true }).click();
        await expect(page).toHaveURL('/zh-cn/account');
        const signedIn = (await (await context.request.get('/api/auth/get-session')).json());
        expect(signedIn.user.email).toBe(email); expect(signedIn.user.username).toBeFalsy();
        await page.goto('/en-us/account/security');
        const initialIdentities = page.getByRole('region', { name: 'Third-party accounts', exact: true });
        await expect(initialIdentities.locator('.social-account').filter({ hasText: connectionName }).locator('.provider-icon img')).toHaveAttribute('src', iconUrl);
        await initialIdentities.getByRole('button', { name: `Link ${secondConnectionName}`, exact: true }).click();
        const bindingDialog = page.locator('md-dialog.form-dialog');
        await expect(bindingDialog.getByRole('button', { name: `Continue linking ${secondConnectionName}`, exact: true })).toHaveCount(0);
        await bindingDialog.getByRole('button', { name: `Continue with ${connectionName}`, exact: true }).click();
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        const reauthenticated = await (await context.request.get('/api/auth/get-session')).json();
        expect(reauthenticated.user.id).toBe(signedIn.user.id);
        expect(reauthenticated.session.id).not.toBe(signedIn.session.id);
        // The selected connector is restored after reauthentication rotates the session.
        await bindingDialog.getByRole('button', { name: `Continue linking ${secondConnectionName}`, exact: true }).click();
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        await expect(initialIdentities.getByText('Linked', { exact: true })).toHaveCount(2);
        const passwordCard = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'Set a password', exact: true }) });
        await expect(page.getByLabel('New password', { exact: true })).toHaveCount(0);
        await passwordCard.getByRole('button', { name: 'Set a password', exact: true }).click();
        const passwordDialog = page.locator('md-dialog.form-dialog');
        await expect(passwordDialog.getByLabel('New password', { exact: true })).toHaveCount(0);
        await passwordDialog.getByRole('button', { name: `Continue with ${connectionName}`, exact: true }).click();
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        await passwordDialog.getByLabel('New password', { exact: true }).fill(password);
        await passwordDialog.getByLabel('Confirm password', { exact: true }).fill(password);
        await passwordDialog.getByRole('button', { name: 'Set a password', exact: true }).click();
        await expect(passwordDialog).toHaveCount(0);
        await expect(page.getByRole('heading', { name: 'Change password', exact: true })).toBeVisible();
        const identities = page.getByRole('region', { name: 'Third-party accounts', exact: true });
        // A linked provider has an unlink action; it cannot appear as unlinked.
        await expect(identities.getByRole('button', { name: `Link ${connectionName}`, exact: true })).toHaveCount(0);
        await identities.getByRole('button', { name: `Unlink ${connectionName}`, exact: true }).click();
        const unlinkDialog = page.locator('md-dialog.form-dialog');
        await unlinkDialog.getByLabel('Current password', { exact: true }).fill(password);
        await unlinkDialog.getByRole('button', { name: 'Verify and continue', exact: true }).click();
        await unlinkDialog.getByRole('button', { name: `Confirm unlinking ${connectionName}`, exact: true }).click();
        await identities.getByRole('button', { name: `Link ${connectionName}`, exact: true }).click();
        const linkDialog = page.locator('md-dialog.form-dialog');
        await linkDialog.getByLabel('Current password', { exact: true }).fill(password);
        await linkDialog.getByRole('button', { name: 'Verify and continue', exact: true }).click();
        await linkDialog.getByRole('button', { name: `Continue linking ${connectionName}`, exact: true }).click();
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        await expect(identities.getByText('Linked', { exact: true })).toHaveCount(2);
        await expect(identities.getByRole('combobox')).toHaveCount(0);
        const mfa = page.locator('section.card').filter({ has: page.getByRole('heading', { name: 'Two-factor authentication', exact: true }) });
        await mfa.getByRole('button', { name: 'Set up authenticator', exact: true }).click();
        const enrollment = page.locator('md-dialog.form-dialog');
        await enrollment.getByLabel('Account password', { exact: true }).fill(password);
        await enrollment.getByRole('button', { name: 'Verify and continue', exact: true }).click();
        await enrollment.getByRole('button', { name: 'Set up authenticator', exact: true }).click();
        // The setup key is exposed as a read-only Material field for manual setup.
        const keyField = enrollment.getByLabel('Setup key', { exact: true });
        const setupKey = await keyField.inputValue();
        const recovery = await enrollment.locator('.mfa-backup-codes li').first().innerText();
        await enrollment.getByLabel('Authenticator code', { exact: true }).fill(await authenticatorCode(`otpauth://totp/Test?secret=${setupKey}`));
        await enrollment.getByRole('checkbox').check();
        await enrollment.getByRole('button', { name: 'Verify and enable', exact: true }).click();
        await expect(mfa.getByText('Two-factor authentication is on.', { exact: true })).toBeVisible();
        await context.request.post('/api/auth/sign-out', { headers: { Origin: testOrigin }, data: {} });
        const verifier = 'b'.repeat(43), challenge = createHash('sha256').update(verifier).digest('base64url');
        await page.goto(`/api/auth/oauth2/authorize?${new URLSearchParams({ client_id: clientId, redirect_uri: 'https://social-app.example.com/callback', response_type: 'code', scope: 'openid profile email', state: 'social-browser-state', nonce: 'social-browser-nonce', code_challenge: challenge, code_challenge_method: 'S256', prompt: 'login', ui_locales: 'en-US' })}`);
        await page.getByRole('button', { name: `Continue with ${connectionName}`, exact: true }).click();
        await expect(page).toHaveURL(/\/en-us\/two-factor\?social=1&flow=/);
        expect(await (await context.request.get('/api/auth/get-session')).json()).toBeNull();
        await page.getByRole('button', { name: 'Use a recovery code', exact: true }).click();
        await page.getByLabel('Recovery code', { exact: true }).fill(recovery);
        await page.getByRole('button', { name: 'Verify sign-in', exact: true }).click();
        await page.getByRole('button', { name: 'Continue', exact: true }).click();
        await expect(page.getByRole('heading', { name: 'Authorize application' })).toBeVisible();
        await page.getByRole('button', { name: 'Allow', exact: true }).click();
        await expect(page).toHaveURL(/https:\/\/social-app\.example\.com\/callback\?/);
        const result = new URL(page.url()); expect(result.searchParams.get('state')).toBe('social-browser-state'); expect(result.searchParams.get('code')).toBeTruthy();
        await page.screenshot({ path: test.info().outputPath('social-completed.png') });
    } finally {
        if (clientId) removeLocalApplications([clientId]);
        removeLocalFixtures([administrator, email]);
        for (const id of [connectionId, secondConnectionId].filter(Boolean)) executeLocal(`DELETE FROM "socialFlow" WHERE "connectionId" = '${id}'; DELETE FROM "socialConnection" WHERE "id" = '${id}';`);
    }
});
